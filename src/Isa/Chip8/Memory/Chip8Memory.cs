using Mechanism;

namespace Chip8.Memory;

public sealed class Chip8Memory : IMemory {
    private static readonly byte[] FontSprites = [
        0xF0, 0x90, 0x90, 0x90, 0xF0, // 0
        0x20, 0x60, 0x20, 0x20, 0x70, // 1
        0xF0, 0x10, 0xF0, 0x80, 0xF0, // 2
        0xF0, 0x10, 0xF0, 0x10, 0xF0, // 3
        0x90, 0x90, 0xF0, 0x10, 0x10, // 4
        0xF0, 0x80, 0xF0, 0x10, 0xF0, // 5
        0xF0, 0x80, 0xF0, 0x90, 0xF0, // 6
        0xF0, 0x10, 0x20, 0x40, 0x40, // 7
        0xF0, 0x90, 0xF0, 0x90, 0xF0, // 8
        0xF0, 0x90, 0xF0, 0x10, 0xF0, // 9
        0xF0, 0x90, 0xF0, 0x90, 0x90, // A
        0xE0, 0x90, 0xE0, 0x90, 0xE0, // B
        0xF0, 0x80, 0x80, 0x80, 0xF0, // C
        0xE0, 0x90, 0x90, 0x90, 0xE0, // D
        0xF0, 0x80, 0xF0, 0x80, 0xF0, // E
        0xF0, 0x80, 0xF0, 0x80, 0x80, // F
    ];

    private readonly byte[] _data = new byte[4096];

    public Chip8Memory() => Chip8Memory.FontSprites.CopyTo(_data, 0);

    public ulong Read(ulong address, int bytes) {
        ulong result = 0;
        for (var i = 0; i < bytes; i++) result = (result << 8) | _data[address + (ulong)i];
        return result;
    }

    public void Write(ulong address, ulong value, int bytes) {
        for (int i = bytes - 1; i >= 0; i--) {
            _data[address + (ulong)i] = (byte)(value & 0xFF);
            value >>= 8;
        }
    }

    public void Load(ulong address, ReadOnlySpan<byte> data) =>
        data.CopyTo(_data.AsSpan((int)address));

    public void Reset() {
        Array.Clear(_data);
        Chip8Memory.FontSprites.CopyTo(_data, 0);
    }
}